// Integrations Vault: each company's own API keys, encrypted with AES-256-GCM.
// The browser only ever sees masked hints (sk-••••1234) and non-secret config.
import TenantIntegration from '../../models/TenantIntegration.js';
import ApiError from '../../utils/ApiError.js';
import env from '../../config/env.js';
import { encrypt, decrypt, maskSecret } from '../../utils/crypto.js';
import { INTEGRATION_PROVIDERS, publicCatalog } from '../../config/integrationProviders.js';
import { recordAudit } from '../audit/auditService.js';
import { getEffectivePlan } from '../billing/planResolver.js';
import { runTester } from './testers.js';

export const listProviders = () => publicCatalog();

const mapToObject = (m) => (m instanceof Map ? Object.fromEntries(m) : { ...(m || {}) });

export function toPublic(doc) {
  return {
    id: String(doc._id),
    provider: doc.provider,
    name: INTEGRATION_PROVIDERS[doc.provider]?.name || doc.provider,
    label: doc.label,
    status: doc.status,
    maskedHints: mapToObject(doc.maskedHints),
    config: mapToObject(doc.config),
    lastTestedAt: doc.lastTestedAt,
    lastError: doc.lastError,
    lastUsedAt: doc.lastUsedAt,
    createdAt: doc.createdAt,
    updatedAt: doc.updatedAt,
  };
}

const audit = (actor, action, provider, metadata = {}) =>
  recordAudit({
    actorType: actor?.userId ? 'USER' : 'SYSTEM',
    actorId: actor?.userId || null,
    tenantId: actor?.tenantId,
    action,
    targetType: 'TenantIntegration',
    metadata: { provider, ...metadata },
  });

const readSecrets = (doc) => JSON.parse(decrypt(doc.encryptedCredentials));

export async function listIntegrations() {
  const docs = await TenantIntegration.find({}).sort({ provider: 1 }).limit(100); // tenant plugin scopes it
  return docs.map(toPublic);
}

export async function saveIntegration(actor, provider, { label, credentials = {}, config = {} }) {
  const meta = INTEGRATION_PROVIDERS[provider];
  if (meta.connectType === 'OAUTH') {
    throw ApiError.badRequest(
      meta.availableInPhase
        ? `${meta.name} is connected by logging in — available in Phase ${meta.availableInPhase}.`
        : `${meta.name} is connected with the "Connect" (login) button, not by pasting a key.`
    );
  }
  if (meta.connectType === 'EXTENSION') throw ApiError.badRequest(`${meta.name} has nothing to connect here — use the Chrome extension.`);
  if (meta.connectType === 'GENERATED') throw ApiError.badRequest(`${meta.name} keys are generated by the platform — use the "Create" button.`);

  const existing = await TenantIntegration.findOne({ provider }).select('+encryptedCredentials');
  const secrets = existing ? readSecrets(existing) : {};
  const changedSecrets = [];
  for (const [k, v] of Object.entries(credentials)) {
    if (v) {
      secrets[k] = v; // '' = keep the stored value
      changedSecrets.push(k);
    }
  }
  const mergedConfig = existing ? mapToObject(existing.config) : {};
  for (const [k, v] of Object.entries(config)) {
    if (v === '') delete mergedConfig[k];
    else mergedConfig[k] = String(v);
  }

  const missing = [
    ...meta.secretFields.filter((f) => !secrets[f.key]).map((f) => f.key),
    ...meta.configFields.filter((f) => f.required && !mergedConfig[f.key]).map((f) => f.key),
  ];
  if (missing.length) {
    throw ApiError.badRequest('Validation failed', missing.map((f) => ({ field: f, message: 'is required' })));
  }

  const update = {
    label: label ?? existing?.label ?? '',
    encryptedCredentials: encrypt(JSON.stringify(secrets)),
    maskedHints: Object.fromEntries(meta.secretFields.map((f) => [f.key, maskSecret(secrets[f.key])])),
    config: mergedConfig,
    status: 'NOT_TESTED', // any change must be re-tested
    lastError: null,
    updatedBy: actor.userId,
  };

  let doc;
  try {
    if (existing) {
      doc = await TenantIntegration.findOneAndUpdate({ _id: existing._id }, { $set: update }, { new: true });
    } else {
      doc = await TenantIntegration.create({ provider, ...update, createdBy: actor.userId });
    }
  } catch (err) {
    if (err.code === 11000) throw ApiError.conflict('This integration was just saved by someone else — please reload');
    throw err;
  }

  // Only field NAMES are logged — never values
  await audit(actor, existing ? 'integration.updated' : 'integration.created', provider, {
    secretsChanged: changedSecrets,
    configFields: Object.keys(config),
  });
  return toPublic(doc);
}

async function loadOrFail(provider, withSecrets = false) {
  const q = TenantIntegration.findOne({ provider });
  if (withSecrets) q.select('+encryptedCredentials');
  const doc = await q;
  if (!doc) throw ApiError.notFound('Integration not connected');
  return doc;
}

export async function testIntegration(actor, provider) {
  const doc = await loadOrFail(provider, true);
  if (doc.status === 'DISABLED') throw ApiError.badRequest('Enable this integration before testing it');

  const result = await runTester(provider, readSecrets(doc), mapToObject(doc.config));
  const updated = await TenantIntegration.findOneAndUpdate(
    { _id: doc._id },
    { $set: { status: result.ok ? 'CONNECTED' : 'ERROR', lastTestedAt: new Date(), lastError: result.ok ? null : result.message } },
    { new: true }
  );
  await audit(actor, 'integration.tested', provider, { ok: result.ok });
  return { integration: toPublic(updated), result };
}

export async function setEnabled(actor, provider, enabled) {
  const doc = await loadOrFail(provider);
  doc.status = enabled ? 'NOT_TESTED' : 'DISABLED';
  doc.updatedBy = actor.userId;
  await doc.save();
  await audit(actor, enabled ? 'integration.enabled' : 'integration.disabled', provider);
  return toPublic(doc);
}

export async function deleteIntegration(actor, provider) {
  const result = await TenantIntegration.deleteOne({ provider });
  if (!result.deletedCount) throw ApiError.notFound('Integration not connected');
  await audit(actor, 'integration.deleted', provider);
  return { deleted: true };
}

/**
 * INTERNAL ONLY (never called by a route): returns decrypted credentials for a server-side job.
 * Every use is audit-logged with its purpose. Must run inside the tenant context.
 */
export async function getCredentials(provider, { purpose, actor = null } = {}) {
  if (!purpose) throw new Error('getCredentials requires a purpose');
  const doc = await TenantIntegration.findOne({ provider, status: { $in: ['CONNECTED', 'NOT_TESTED'] } }).select('+encryptedCredentials');
  if (!doc) return null;
  await TenantIntegration.updateOne({ _id: doc._id }, { $set: { lastUsedAt: new Date() } });
  await audit({ userId: actor?.userId, tenantId: doc.tenantId }, 'integration.used', provider, { purpose });
  return { secrets: readSecrets(doc), config: mapToObject(doc.config) };
}

/**
 * AI key resolution order (spec): the company's own key → platform default key (only if the plan includes it).
 * Returns { source: 'TENANT'|'PLATFORM', provider, apiKey } or null.
 */
export async function resolveAiCredentials(tenantId, { purpose }) {
  for (const provider of ['OPENAI', 'ANTHROPIC']) {
    const creds = await getCredentials(provider, { purpose });
    if (creds) return { source: 'TENANT', provider, apiKey: creds.secrets.apiKey, config: creds.config };
  }
  const plan = await getEffectivePlan(tenantId);
  if ((plan.features || []).includes('platform-ai')) {
    if (env.PLATFORM_OPENAI_API_KEY) return { source: 'PLATFORM', provider: 'OPENAI', apiKey: env.PLATFORM_OPENAI_API_KEY, config: {} };
    if (env.PLATFORM_ANTHROPIC_API_KEY) return { source: 'PLATFORM', provider: 'ANTHROPIC', apiKey: env.PLATFORM_ANTHROPIC_API_KEY, config: {} };
  }
  return null;
}

/** Super admin: status only — no secrets, no masked hints, no config. */
export async function adminIntegrationStatus(tenantId) {
  const docs = await TenantIntegration.find({ tenantId }).limit(100);
  return docs.map((d) => ({
    provider: d.provider,
    name: INTEGRATION_PROVIDERS[d.provider]?.name || d.provider,
    status: d.status,
    lastTestedAt: d.lastTestedAt,
    lastUsedAt: d.lastUsedAt,
    updatedAt: d.updatedAt,
  }));
}
